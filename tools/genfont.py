#!/usr/bin/env python3
"""fonts/amiga8.txt -> Sources/CAmiga/font8.c : 256 glyphs of 8x8 (bit 7 = left).

Latin-1 accented letters are composed from the base letter and an accent;
capitals lose one duplicated row to make room for the accent.
"""
import sys
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])
glyphs = {}
cur, rows = None, []
for ln in src.read_text().splitlines():
    if ln.startswith("# ") or not ln.strip():
        continue
    if ln.startswith("= "):
        cur = " " if ln[2:] == "space" else ln[2:]
        rows = []
        glyphs[cur] = rows
        continue
    rows.append(ln.ljust(7, ".")[:7])

def bits(rows):
    return [sum(1 << (7 - i) for i, ch in enumerate(r) if ch == "#") for r in rows]

ACC = {  # two-row accents for lowercase, one-row variant for capitals
    "grave": ([".##....", "..##..."], "..##..."),
    "acute": (["...##..", "..##..."], "...##.."),
    "circ":  (["..##...", ".##.##."], "..###.."),
    "tilde": ([".##.##.", "##.##.."], ".#####."),
    "uml":   ([".......", ".##.##."], ".##.##."),
    "ring":  (["..##...", ".#..#.."], "..###.."),
}

def lower(base, acc):
    g = list(glyphs[base])
    a = ACC[acc][0]
    if base == "i":
        g[0], g[1] = a[0], a[1]
    else:
        g[0], g[1] = a
    return g

def upper(base, acc):
    g = list(glyphs[base])
    drop = next((i for i in range(1, 6) if g[i] == g[i - 1] or g[i] == g[i + 1]), 1)
    g = g[:drop] + g[drop + 1:]
    return [ACC[acc][1]] + g[:6] + [g[6] if len(g) > 6 else "......."]

table = {ord(k): v for k, v in glyphs.items()}
comp = {
    0xC0: ("A", "grave"), 0xC1: ("A", "acute"), 0xC2: ("A", "circ"), 0xC3: ("A", "tilde"),
    0xC4: ("A", "uml"), 0xC5: ("A", "ring"), 0xC8: ("E", "grave"), 0xC9: ("E", "acute"),
    0xCA: ("E", "circ"), 0xCB: ("E", "uml"), 0xCC: ("I", "grave"), 0xCD: ("I", "acute"),
    0xCE: ("I", "circ"), 0xCF: ("I", "uml"), 0xD1: ("N", "tilde"), 0xD2: ("O", "grave"),
    0xD3: ("O", "acute"), 0xD4: ("O", "circ"), 0xD5: ("O", "tilde"), 0xD6: ("O", "uml"),
    0xD9: ("U", "grave"), 0xDA: ("U", "acute"), 0xDB: ("U", "circ"), 0xDC: ("U", "uml"),
    0xDD: ("Y", "acute"),
}
for code, (b, a) in comp.items():
    table[code] = upper(b, a)
    table[code + 0x20] = lower(b.lower(), a)
table[0xFF] = lower("y", "uml")
# cedillas
table[0xE7] = glyphs["c"][:7] + ["..##..."]
table[0xC7] = glyphs["C"][:7] + ["..##..."]
extra = {
    0xAB: [".......", "..#..#.", ".#..#..", "#..#...", ".#..#..", "..#..#.", ".......", "......."],
    0xBB: [".......", "#..#...", ".#..#..", "..#..#.", ".#..#..", "#..#...", ".......", "......."],
    0xB0: ["..###..", ".##.##.", "..###..", ".......", ".......", ".......", ".......", "......."],
    0xA9: [".#####.", "#.....#", "#.###.#", "#.#...#", "#.###.#", "#.....#", ".#####.", "......."],
    0xA3: ["..###..", ".##.##.", ".##....", "####...", ".##....", ".##..##", "######.", "......."],
    0xB7: [".......", ".......", ".......", "..##...", ".......", ".......", ".......", "......."],
    0xDF: [".####..", "##..##.", "##..##.", "##.##..", "##..##.", "##..##.", "##.##..", "##....."],
    0xA0: ["......."] * 8,
}
table.update(extra)
box = ["######.", "##..##.", "##..##.", "##..##.", "##..##.", "######.", ".......", "......."]

lines = ["/* generated by tools/genfont.py from fonts/amiga8.txt - do not edit */",
         "#include <stdint.h>", "const uint8_t font8_data[256][8] = {"]
for c in range(256):
    if c < 32 or c == 127 or (128 <= c < 160):
        g = ["......."] * 8
    else:
        g = table.get(c, box)
    lines.append("    {" + ", ".join(f"0x{b:02X}" for b in bits(g)) + "},")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(f"{len(glyphs)} glyphes dessinés, {len(comp) * 2 + 3} composés")
