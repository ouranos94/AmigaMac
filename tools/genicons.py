#!/usr/bin/env python3
"""fonts/icons.txt -> Sources/CAmiga/icons_default.c (2-plane Amiga image data)."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'fonts', 'icons.txt')
dst = os.path.join(here, '..', 'Sources', 'CAmiga', 'icons_default.c')
pens = {'.': 0, '#': 1, 'o': 2, '*': 3}
icons, cur = [], None
for line in open(src, encoding='utf-8'):
    line = line.rstrip('\n')
    if line.startswith('# ') or line == '#' or not line:
        continue
    if line.startswith('icon '):
        cur = (line[5:].strip(), [])
        continue
    if line == 'end':
        icons.append(cur); cur = None
        continue
    cur[1].append(line)
out = ['/* generated by tools/genicons.py from fonts/icons.txt - do not edit */',
       '#include <stdint.h>', '#include "icons_default.h"', '']
table = []
for name, rows in icons:
    w, h = len(rows[0]), len(rows)
    if any(len(r) != w for r in rows):
        sys.exit('icon %s: ragged rows' % name)
    words = (w + 15) // 16
    data = []
    for plane in range(2):
        for r in rows:
            bits = [((pens[ch] >> plane) & 1) for ch in r] + [0] * (words * 16 - w)
            for i in range(0, len(bits), 8):
                b = 0
                for k in range(8):
                    b = (b << 1) | bits[i + k]
                data.append(b)
    out.append('static const uint8_t icon_%s[%d] = {' % (name, len(data)))
    for i in range(0, len(data), 16):
        out.append('    ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    out.append('};')
    table.append('    { "%s", %d, %d, icon_%s },' % (name, w, h, name))
out.append('')
out.append('const DefIcon default_icons[] = {')
out += table
out.append('    { 0, 0, 0, 0 }')
out.append('};')
open(dst, 'w').write('\n'.join(out) + '\n')
