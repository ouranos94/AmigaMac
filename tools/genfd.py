#!/usr/bin/env python3
"""Generate Sources/CAmiga/fdtables.c from the NDK .fd files.

Each library gets its full vector table (LVO, name, argument registers), so
every library built at boot has correct offsets even for functions that are
not implemented natively yet.
Usage: genfd.py <fd dir> <output.c>
"""
import re
import sys
from pathlib import Path

# exec entries the NDK hides as execPrivateN (1.3 includes / AROS names)
EXEC_PRIVATE = {36: "ExitIntr", 42: "Schedule", 48: "Reschedule", 54: "Switch",
                60: "Dispatch", 66: "Exception", 504: "RawIOInit", 510: "RawMayGetChar",
                516: "RawPutChar", 738: "ChildFree", 744: "ChildOrphan", 750: "ChildStatus",
                756: "ChildWait", 810: "TaggedOpenLibrary"}


def parse(path):
    funcs, lvo = [], 30
    for ln in path.read_text(encoding="latin1").splitlines():
        ln = ln.strip()
        if ln.startswith("##bias"):
            lvo = int(ln.split()[1])
        elif ln.startswith("##end"):
            break
        elif ln and not ln.startswith(("#", "*")):
            m = re.match(r"([A-Za-z0-9_]+)\(([^)]*)\)\(([^)]*)\)", ln)
            if not m:
                continue
            name, regs = m.group(1), m.group(3).lower().replace(",", "/")
            if path.name == "exec_lib.fd":
                name = EXEC_PRIVATE.get(lvo, name)
            funcs.append((lvo, name, regs))
            lvo += 6
    return funcs


def main():
    fd_dir, out = Path(sys.argv[1]), Path(sys.argv[2])
    libs = []
    for p in sorted(fd_dir.glob("*_lib.fd")):
        libs.append((p.stem[:-4], parse(p)))
    lines = ['/* generated by tools/genfd.py from the NDK .fd files - do not edit */',
             '#include "os.h"', '']
    for stem, funcs in libs:
        lines.append(f"static const FdFunc fd_{stem}[] = {{")
        for lvo, name, regs in funcs:
            lines.append(f'    {{ {lvo}, "{name}", "{regs}" }},')
        lines.append("};")
    lines.append("const FdLib fd_libs[] = {")
    for stem, funcs in libs:
        lines.append(f'    {{ "{stem}", fd_{stem}, {len(funcs)} }},')
    lines.append("};")
    lines.append(f"const int fd_lib_count = {len(libs)};")
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(libs)} bibliothèques, {sum(len(f) for _, f in libs)} fonctions")


if __name__ == "__main__":
    main()
